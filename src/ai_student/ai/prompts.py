PROMPTS: dict[str, str] = {
    "asr": PROMPT_ASR,
    "vision_board": PROMPT_VISION_BOARD,
    "notes_merge": PROMPT_NOTES_MERGE,
    "task_extract": PROMPT_TASK_EXTRACT,
    "solve": PROMPT_SOLVE,
    "self_check": PROMPT_SELF_CHECK,
    "summary": PROMPT_SUMMARY,
    "agent_supervisor": PROMPT_AGENT_SUPERVISOR,
}


def prompt_keys() -> list[str]:
    """可用提示词键（GUI 的提示词覆盖编辑器用）。"""
    return list(PROMPTS)


def get_prompt(key: str, overrides: dict[str, str] | None = None) -> str:
    """取提示词；overrides 里同名的非空项优先（对应 AppConfig.prompt_overrides）。"""
    name = (key or "").strip()
    if name not in PROMPTS:
        raise KeyError(f"未知提示词：{key}（可用：{'、'.join(PROMPTS)}）")
    custom = (overrides or {}).get(name)
    if isinstance(custom, str) and custom.strip():
        return custom.rstrip()
    return PROMPTS[name]


def render(template: str, **values: object) -> str:
    """安全格式化：缺失的占位符原样保留，None 变成空串，不会抛 KeyError。"""
    class _Safe(dict):
        def __missing__(self, key: str) -> str:
            return "{" + key + "}"

    data = {k: ("" if v is None else v) for k, v in values.items()}
    return (template or "").format_map(_Safe(data))
